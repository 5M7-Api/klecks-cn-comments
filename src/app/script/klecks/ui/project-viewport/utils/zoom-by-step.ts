/**
 * 它保证了：不管你现在是在 10% 还是 3000%，你每次滚动滚轮，
 * 画面永远以一个恒定的“乘法比例”（比如永远比上一帧大 1.25 倍）在变化，
 * 从而让视觉感受达到绝对的匀速和平滑。
 */

export function zoomByStep(oldScale: number, stepNum: number): number {
    // 1. 【降维打击：转入对数空间】
    // 将当前的缩放比例转换到以 2 为底的对数空间 (Logarithmic Space)。
    // 举例：如果是 1倍(100%) -> 得 0；如果是 2倍(200%) -> 得 1；如果是 0.5倍(50%) -> 得 -1。
    const step = Math.log2(oldScale);

    // 2. 【网格映射】
    // stepNum 是传入的步长，比如 0.25 (代表每次放大 1/4 档) 或 -0.5 (缩小 1/2 档)。
    // 这里把当前的对数步长，除以步幅绝对值，计算出当前在“缩放网格”上的精确坐标。
    let newStep = step / Math.abs(stepNum);
    // 3. 【前进或后退】
    // 根据 stepNum 的正负，决定是向右（放大，+1格）还是向左（缩小，-1格）。
    newStep += stepNum > 0 ? 1 : -1;
    // 4. 【灵魂机制：吸附 (Snap to Grid)】
    // 极其关键的一步！对坐标进行四舍五入，强制对齐到最近的整数档位。
    // 这能把那些因为“适应屏幕”产生的无限不循环小数（比如 87.3%），强行掰回标准的整齐档位上。
    newStep = Math.round(newStep);
    // 5. 【恢复真实步长】
    // 把对齐后的网格坐标，重新乘回原来的步幅，得到最终的对数幂次。
    newStep *= Math.abs(stepNum);

    // 6. 【升维：还原真实缩放比】
    // 用 2 的幂次方把对数还原回真实的缩放比例。
    return Math.pow(2, newStep);
}
